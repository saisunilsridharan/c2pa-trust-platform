import assert from 'node:assert/strict';
import {test, beforeEach, after} from 'node:test';
import {readFile, writeFile, mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import ts from 'typescript';
const calls=[];
globalThis.location={origin:'https://portal.test'};
globalThis.fetch=async(input,options)=>{calls.push({input,headers:new Headers(options?.headers)});return new Response('{}');};
const directory=await mkdtemp(join(tmpdir(),'c2pa-client-context-'));
const source=await readFile(new URL('../src/portalFetch.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const target=join(directory,'context.mjs');await writeFile(target,compiled);
const {setActiveWorkspace,workspaceFetch,portalFetch}=await import(pathToFileURL(target));
beforeEach(()=>{calls.length=0;setActiveWorkspace(1);});
after(()=>rm(directory,{recursive:true,force:true}));
test('pending component requests retain their selected workspace after a switch',async()=>{const pending=workspaceFetch();setActiveWorkspace(2);await pending('/api/v1/jobs',{method:'POST'});assert.equal(calls[0].headers.get('X-Workspace-Id'),'1');});
test('new components use the newly selected workspace',async()=>{setActiveWorkspace(2);await workspaceFetch()('/api/v1/admin/configuration');assert.equal(calls[0].headers.get('X-Workspace-Id'),'2');});
test('explicit connection selection overrides a component snapshot',async()=>{const pending=workspaceFetch();await pending('/api/v1/auth/me',{headers:{'X-Workspace-Id':'3'}});assert.equal(calls[0].headers.get('X-Workspace-Id'),'3');});
test('workspace context is never added to a different origin',async()=>{await workspaceFetch()(new URL('https://private-service.test/api/v1/jobs'));assert.equal(calls[0].headers.get('X-Workspace-Id'),null);});
test('unselected sign-in requests allow the server to choose an accessible workspace',async()=>{setActiveWorkspace(null);await portalFetch('/api/v1/auth/me');assert.equal(calls[0].headers.get('X-Workspace-Id'),null);});
